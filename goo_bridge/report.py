"""Human and machine readable reports for GOO Bridge."""

from __future__ import annotations

import html
import json
from pathlib import Path
from typing import Any

from .fsutil import atomic_write_text


def summarize(analysis: dict[str, Any]) -> dict[str, Any]:
    groups = analysis.get("goo_groups") or []
    missing = analysis.get("missing_files") or []
    return {
        "file": analysis.get("name") or analysis.get("file") or "",
        "blender": analysis.get("blender_version", ""),
        "goo_groups": len(groups),
        "group_names": list(groups),
        "objects": int(analysis.get("objects", 0)),
        "materials": int(analysis.get("materials", 0)),
        "external_files": len(analysis.get("external_files") or []),
        "missing_files": len(missing),
        "missing": [item.get("path", "") for item in missing],
        "features": analysis.get("features") or {},
    }


def write_json(report: dict[str, Any], path: Path) -> Path:
    atomic_write_text(path, json.dumps(report, indent=2, ensure_ascii=True) + "\n")
    return path


def write_html(analysis: dict[str, Any], path: Path) -> Path:
    summary = summarize(analysis)
    groups = "".join(f"<li>{html.escape(str(name))}</li>" for name in summary["group_names"])
    missing = "".join(f"<li>{html.escape(str(name))}</li>" for name in summary["missing"])
    features = "".join(
        f"<tr><td>{html.escape(str(key))}</td><td>{'yes' if value else 'no'}</td></tr>"
        for key, value in summary["features"].items()
    )
    document = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>GOO Bridge analysis - {html.escape(summary['file'])}</title>
<style>
body{{font:15px system-ui,sans-serif;max-width:900px;margin:2rem auto;color:#222}}
h1{{font-size:1.4rem}} table{{border-collapse:collapse;width:100%}}
td,th{{border:1px solid #ccc;padding:.35rem .5rem;text-align:left}}
.ok{{color:#146c2e}} .warn{{color:#9a5b00}}
</style></head><body>
<h1>GOO Bridge analysis</h1>
<p><b>File:</b> {html.escape(summary['file'])}<br>
<b>Blender:</b> {html.escape(str(summary['blender']))}<br>
<b>GOO groups:</b> {summary['goo_groups']} &nbsp; <b>Objects:</b> {summary['objects']}
&nbsp; <b>Missing files:</b> <span class="{'warn' if summary['missing_files'] else 'ok'}">{summary['missing_files']}</span></p>
<h2>GOO node groups</h2><ul>{groups or '<li>none</li>'}</ul>
<h2>Missing external files</h2><ul>{missing or '<li>none</li>'}</ul>
<h2>Feature flags</h2><table><tr><th>Flag</th><th>Value</th></tr>{features}</table>
<p>Generated by GOO Bridge. Remote and compatibility reports are produced by their own commands.</p>
</body></html>
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(path, document)
    return path
